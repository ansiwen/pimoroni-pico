/*
Driver for HUB75 panels built with S-PWM ("PWM type") LED driver chips.

Unlike classic HUB75 panels, which are made of plain shift registers that we
must refresh continuously with binary coded modulation, these chips hold the
greyscale data for the whole panel in internal SRAM and generate the PWM
themselves. They need a reference clock (DCLK on the CLK line) and a row-switch
clock (GCLK on the OE line), both generated by PIO. The frame is re-sent at a
fixed rate (60Hz) in the background, since uploads at irregular intervals make the
whole picture flicker.

Based on the DMD_STM32 library by Dmitry Dmitriev (board707):
https://github.com/board707/DMD_STM32 (DMD_SPWM_Driver_RP.h)

Supported chips (all use the "decoupled" DCLK/GCLK scheme):
 - SM16380SH
 - ICND2055
 - FM6373

Panels that don't have two halves at 1/32 scan, or use a shift register as row
driver, need `lanes` and `row_driver`, eg. a 128x64 1/64 scan FM6373 panel:
Lanes::SINGLE and RowDriver::SHIFT_REGISTER.

SPDX-License-Identifier: GPL-3.0-or-later
*/

namespace pimoroni {

class Hub75SPWM {
    public:
    enum class Chip {
        SM16380SH,
        ICND2055,
        FM6373,
    };

    // Which pixels the two sets of data lines (lanes) drive. Each scan line,
    // both lanes send `chain` pixels, one channel of a chip each.
    enum class Lanes {
        // R0, G0, B0 the top half, R1, G1, B1 the bottom half, eg. 1/32 scan on
        // 64 rows: height / 2 scan lines, chain = width
        HALVES,
        // Only R0, G0, B0: height scan lines, chain = width
        SINGLE,
        // R0, G0, B0 the left half, R1, G1, B1 the right half: height scan
        // lines, chain = width / 2
        LEFT_RIGHT,
    };

    // How the rows are selected
    enum class RowDriver {
        // A-E are a binary row address, up to 32 rows (74HC138-like decoders,
        // SM5166, RUC7258, ...)
        DECODER,
        // A shift register with a single active output, eg. for 1/64 scan:
        // clocked once per scan line, see row_shift_clk, _lat and _data
        SHIFT_REGISTER,
    };

    uint width;
    uint height;
    Chip chip;
    Lanes lanes = Lanes::HALVES;
    uint scan_lines;    // number of multiplexed rows (scan lines)
    uint chain;         // pixels per lane and scan line, a multiple of 16

    // 0 (off) - 255 (full brightness)
    uint8_t brightness = 255;

    // Number of significant bits (1 - 10) of the gamma corrected colour
    // sent to the panel. DMD_STM32 only sends 4 bits.
    uint colour_depth = 10;

    // Row selection, applied by start(). For SHIFT_REGISTER, which of A-E
    // (0-4) is the shift register's clock, latch and data input; the latch is
    // high while the data is clocked in, like DMD_STM32's DMD_Mux595. Set
    // row_shift_lat to a value > 4 for row drivers without a latch.
    RowDriver row_driver = RowDriver::DECODER;
    uint row_shift_clk = 0;
    uint row_shift_lat = 1;
    uint row_shift_data = 2;
    bool row_shift_data_inverted = false;  // the selected row is shifted in as 0

    // CLKs per scan line with OE (GCLK) low, high, low, applied from the next
    // frame. 0 for DMD_STM32's: 28, 4, 96, or 38, 4, 86 for SHIFT_REGISTER,
    // which gives the row driver more time to switch.
    uint gclk_d1 = 0;
    uint gclk_d2 = 0;
    uint gclk_d3 = 0;

    // Interstate 75 (W) pinout
    uint pin_r0 = 0;      // R0, G0, B0, R1, G1, B1 must be consecutive
    uint pin_row_a = 6;   // A, B, C, D, E must be consecutive
    uint pin_clk = 11;    // CLK and LAT must be consecutive
    uint pin_lat = 12;
    uint pin_oe = 13;


    // width is the total length of the chain and must be a multiple of 16.
    // `buffer` must hold buffer_size() words, or nullptr to allocate it.
    // `color_order` works as in Hub75.
    Hub75SPWM(uint width, uint height, Chip chip = Chip::SM16380SH, uint32_t *buffer = nullptr,
              Hub75::COLOR_ORDER color_order = Hub75::COLOR_ORDER::RGB);
    ~Hub75SPWM();

    // Replace the chip configuration registers, eg. with a profile from
    // DMD_STM32's register_test/profiles that matches your panel.
    // Register 0x02 (scan lines) is always set to match the panel height.
    // One register is sent with every frame, so all are sent within ~0.5s.
    void set_config_registers(const uint16_t *regs, uint count);
    // As above, with separate values for the red, green and blue drivers
    void set_config_registers(const uint16_t *red, const uint16_t *green, const uint16_t *blue, uint count);
    // Restore the built-in configuration registers for the chip
    void load_chip_defaults();

    // Change the lane layout, only while stopped. Sets scan_lines and chain and
    // clears the frame buffer. Returns false if the frame buffer passed to the
    // constructor is too small.
    bool set_lanes(Lanes lanes);

    // Bit position + 1 of the greyscale MSB in the chips' 16-bit words, 12-15.
    // Chip specific, eg. 13 for the SM16380SH: with a value too high, bright
    // colours clip. Applied from the next frame.
    void set_gclk_bits(uint bits);
    uint get_gclk_bits() const { return gclk_bits; }

    // Size of the frame buffer in 32-bit words: width * height, the same RAM as Hub75
    uint buffer_size() const { return scan_lines * chain * words_per_pixel(); }

    // Brightness and colour depth are applied when a pixel is set.
    // Writes straight to the frame buffer, use update() to avoid tearing.
    void set_pixel(uint x, uint y, uint8_t r, uint8_t g, uint8_t b);
    void clear();

    // For finding out how a panel is wired: set chain position `pos` of `lane`
    // (0: R0, G0, B0, 1: R1, G1, B1) in scan line `line`, whatever the layout
    void set_chain_pixel(uint line, uint pos, uint lane, uint8_t r, uint8_t g, uint8_t b);

    // Start/stop refreshing the panel at the refresh rate in the background (timer and DMA
    // interrupts, ~0.5ms of CPU per frame). Only one instance can run at a time.
    void start();
    void stop();

    // Refresh rate of the background refresh in Hz, default 60. Can be changed
    // while running. Choose a multiple of your frame rate and use update() with
    // `sync`, eg. 50Hz and sync = 2 for 25fps.
    void set_refresh_rate(uint hz);

    // Convert a PicoGraphics frame buffer into the frame buffer, in sync with the
    // background refresh so a frame never shows half of an update (for PEN_RGB888).
    // Takes ~2ms for 128x64 on an RP2350, up to the rest of a running upload (~5ms).
    // It is shown with the frame after the following one (~17-33ms).
    // Can be called from either core.
    // With `sync` > 0, first wait until `sync` frames have been sent since the
    // last update() with `sync`, so each image is shown for exactly `sync`
    // frames, eg. 2 at 50Hz for a steady 25fps. Call it in a loop instead of
    // timing your frames yourself. The image is converted between two frames,
    // so it can't tear and avoid_tearing doesn't matter.
    void update(PicoGraphics *graphics, uint sync = 0);

    // If update() is called while a frame is being sent, wait for the parts of
    // the frame it converts to be sent first, so the frame isn't torn (up to ~5ms).
    // Without this, that frame can show the old image above a line and the new
    // one below it, like Hub75.
    bool avoid_tearing = true;

    // Set the speed of the CLK line: the frame upload and the free-running DCLK
    // (the chips' PWM clock) always run at the same speed, so dark colours don't
    // flicker. The clock is the system clock / (6 * div). The default is the
    // smallest integer divider that keeps it at or below 12.5MHz: 2 at 150MHz,
    // ~5ms per 128x64 frame (for the FM6373 25MHz: 1, ~5.2ms with
    // Lanes::SINGLE). 1 gives 25MHz (~2.6ms per frame), which can cause
    // noise on some panels; an upload must also stay slower than update()
    // converts (~1.9ms for 128x64), see torn_frames. Applied from the next frame.
    // For testing, a divider below 1 (down to 1/3) only makes DCLK faster: the
    // upload stays at div 1, so the clocks differ, which can make dark colours
    // flicker.
    // Commands (VSYNC, latches, registers) always keep their own speed.
    void set_clock_div(float div);
    float get_clock_div() const { return clock_div; }

    // For testing: CPU time of the last background frame start, duration of the
    // last frame upload, and how long the last update() spent waiting for the
    // upload and converting, in microseconds
    volatile uint32_t frame_start_us = 0;
    volatile uint32_t upload_us = 0;
    // Frames that update() didn't convert in time: an upload that started during
    // update() overtook the conversion and sent part of the old image. Should
    // stay 0, otherwise raise the upload clock divider. Doesn't count the tears
    // that avoid_tearing = false allows.
    volatile uint32_t torn_frames = 0;
    uint32_t update_wait_us = 0;
    uint32_t update_convert_us = 0;

    private:
    static const uint MAX_CONFIG_REGISTERS = 48;
    static const uint CHANNELS_PER_CHIP = 16;

    // Position of the colour for the R, G and B pins in an RGB888 colour
    uint pin_shift[3] = {16, 8, 0};

    // Greyscale data as it is clocked out, see hub75_spwm_pack.hpp
    uint32_t *frame_buffer = nullptr;
    bool managed_buffer = false;
    uint buffer_words = 0;   // allocated or passed to the constructor

    // Bit position + 1 of the greyscale MSB in the chip's 16-bit word
    uint gclk_bits = 14;

    uint16_t config_registers[3][MAX_CONFIG_REGISTERS]; // red, green, blue
    uint config_register_count = 0;
    uint next_config_register = 0;

    // State machines
    PIO pio = nullptr;      // data, clk_lat
    PIO pio_gclk = nullptr; // clk_cnt, rows
    uint sm_frame = 0;
    uint sm_regs = 0;
    uint sm_clk_lat = 0;
    uint sm_clk_cnt = 0;
    uint sm_rows = 0;
    uint frame_prog_offs = 0;
    uint regs_prog_offs = 0;
    uint clk_lat_prog_offs = 0;
    uint clk_cnt_prog_offs = 0;
    uint rows_prog_offs = 0;
    const pio_program_t *rows_program = nullptr;
    bool rows_shift_initialised = false;
    pio_sm_config frame_config;
    pio_sm_config regs_config;
    pio_sm_config clk_lat_config;
    pio_sm_config clk_cnt_config;
    pio_sm_config rows_config;

    int dma_channel = -1;

    volatile bool running = false;  // read by update() on the other core

    bool gclk_running = false;

    // Background refresh
    enum class State { IDLE, SYNCING, UPLOADING };
    volatile State state = State::IDLE;
    volatile uint32_t frame_number = 0;
    volatile uint32_t frame_us = 1000000 / 60;
    uint32_t sync_frame = 0;   // frame_number of the last update() with sync
    volatile float clock_div = 0;           // 0 until start()
    volatile uint32_t dclk_clkdiv_reg = 0;  // 3 * clock_div as written to the DCLK SM's CLKDIV register
    uint32_t upload_start_us = 0;
    alarm_id_t frame_alarm = 0;

    static int64_t frame_alarm_callback(alarm_id_t id, void *user_data);
    static void dma_irq_handler();
    int64_t start_frame();
    uint upload_line();
    void finish_frame();
    uint32_t greyscale(uint8_t v);
    void map_pixel(uint x, uint y, uint &pos, uint &line, uint &lane) const;
    // Frame buffer words per chain position: 1 with only R0, G0, B0
    uint words_per_pixel() const { return lanes == Lanes::SINGLE ? 1 : 2; }
    uint32_t row_shift_sequence(bool data) const;
    void row_shift_exec(uint32_t sequence);

    void send_clocks(uint count, bool lat = false);
    void send_latches(uint count) { send_clocks(count, true); }
    void send_oe(uint count);
    void send_vsync();
    void send_register(uint16_t value, uint latches) { send_register(value, value, value, latches); }
    void send_register(uint16_t red, uint16_t green, uint16_t blue, uint latches);
    void start_dma(uint sm, const void *src, uint count, uint ring_bits);
    void wait_dma(uint sm);

    void init_mux();
    void start_gclk();
    void stop_gclk();
    void start_dclk();
    void load_config_register();
};

}
